  function cells(name: string): { x: number; y: number; c: string }[] {
    const rows = ICONS[name] ?? ICONS.sparkle
    const out: { x: number; y: number; c: string }[] = []
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        const ch = row[x]
        if (ch !== '.') out.push({ x, y, c: ch })
      }
    })
    return out
  }
